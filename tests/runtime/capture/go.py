#!/usr/bin/env python3
"""
Capture the runtime call graph of a Go module from its own tests.

Go has no call tracer that is exact and cheap, and callgrind loses track of
goroutine stack switches. So the capture instruments a COPY of the module:
`go/instrument.go` puts `__rt.E();` right after the opening brace of every
function and function literal (and the hook import on the package line, so no
line moves), and `go/rttrace.go` records, at each entry, the callee and the
first caller frame that is not a compiler wrapper (`<autogenerated>`, `-fm`) or
the runtime's defer machinery. Every call is counted, nothing is sampled. A
generated `TestMain` per test package dumps the counts to `$RTTRACE_DIR`.

The tests run as `go test -count=1 -p 2 -vet=off -timeout 5m
-gcflags='all=-N -l' ./...`: no inlining, so a callee keeps its own frame.
Calls from the standard library or a dependency into the project (net/http
calling a handler, testing.tRunner calling a test, `go f()` from
runtime.goexit) have no project caller and are dropped, as are calls into
dependencies. Names are the runtime's, with the import path cut to its last
element: `gin.(*Context).Next`, `binding.mapForm`, `gin.TestX.func1`.

Prerequisites: a Go toolchain new enough for the module (GOTOOLCHAIN is
honoured), git, network for `go mod download` on the first run, ~1.5 GB of
scratch (build cache included). Typical run on gin: a few minutes, most of it
building the dependencies without optimisation.

    python3 tests/runtime/capture/go.py --project gin-gonic/gin \\
        --checkout /tmp/callix-baseline/gin-gonic__gin

The checkout is cloned, never modified; it must be at the ref the artifact
records (benchmarks/projects.json), which is what `runtime.py compare` reads.
"""

from __future__ import annotations

import argparse
import json
import os
import shutil
import subprocess
import sys
import tempfile
from pathlib import Path

HERE = Path(__file__).resolve().parent
ROOT = HERE.parent.parent.parent
sys.path.insert(0, str(HERE))

import common  # noqa: E402

HOOK_DIR = "internal/rttrace"
MAIN_FILE = "zz_rttrace_main_test.go"
TEST_ARGS = [
    "test", "-count=1", "-p", "2", "-vet=off", "-timeout", "5m",
    "-gcflags=all=-N -l", "./...",
]


def short_name(name: str) -> str:
    """`github.com/o/r/pkg.(*T).M` -> `pkg.(*T).M`: the import path's last element."""
    return name[name.rfind("/") + 1:]


def injected(rel: str) -> bool:
    return rel.startswith(HOOK_DIR + "/") or rel.rsplit("/", 1)[-1] == MAIN_FILE


def parse_trace(lines, root):
    """Yield `((file, name, line), (file, name, line), count)` for in-project calls."""
    for raw in lines:
        raw = raw.rstrip("\n")
        if not raw:
            continue
        fields = raw.split("\t")
        if len(fields) != 7:
            raise ValueError(f"bad trace row: {raw!r}")
        ends = []
        for name, file, line in (fields[0:3], fields[3:6]):
            rel = common.relativize(file, root)
            if rel is None or injected(rel) or not rel.endswith(".go"):
                break
            ends.append((rel, short_name(name), int(line)))
        if len(ends) == 2:
            yield ends[0], ends[1], int(fields[6])


def go_env():
    env = dict(os.environ)
    env.setdefault("GOFLAGS", "")
    return env


def module_path(src: Path) -> str:
    for line in (src / "go.mod").read_text(encoding="utf-8").splitlines():
        if line.startswith("module "):
            return line.split()[1]
    raise SystemExit("go.mod has no module line")


def manifest_ref(project: str) -> str | None:
    listed = json.loads((ROOT / "benchmarks" / "projects.json").read_text(encoding="utf-8"))
    items = listed if isinstance(listed, list) else listed.get("projects", [])
    for item in items:
        if item.get("name") == project:
            return str(item["ref"])
    return None


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    parser.add_argument("--project", required=True, help="owner/repo")
    parser.add_argument("--checkout", required=True, help="pristine checkout at the pinned ref")
    parser.add_argument("--ref", help="default: benchmarks/projects.json")
    parser.add_argument("--work", help="scratch directory (default: a temporary one)")
    parser.add_argument("--keep", action="store_true", help="keep the scratch directory")
    parser.add_argument("-o", "--output", help="default: tests/runtime/<owner>__<repo>.json")
    args = parser.parse_args()

    checkout = Path(args.checkout).resolve()
    sha = common.git_sha(checkout)
    if not sha:
        raise SystemExit(f"{checkout} is not a git checkout")
    ref = args.ref or manifest_ref(args.project)
    if not ref:
        raise SystemExit(f"{args.project} is not in benchmarks/projects.json; pass --ref")
    output = Path(args.output or HERE.parent / f"{args.project.replace('/', '__')}.json")
    work = Path(args.work or tempfile.mkdtemp(prefix="callix-go-capture-")).resolve()
    src, raw, tmp = work / "src", work / "raw", work / "tmp"
    for path in (src, raw, tmp):
        if path.exists():
            shutil.rmtree(path)
    raw.mkdir(parents=True)
    tmp.mkdir()
    env = go_env()
    try:
        subprocess.run(["git", "clone", "-q", "--no-checkout", str(checkout), str(src)], check=True)
        subprocess.run(["git", "-C", str(src), "checkout", "-q", sha], check=True)
        module = module_path(src)
        (src / HOOK_DIR).mkdir(parents=True)
        shutil.copy(HERE / "go" / "rttrace.go", src / HOOK_DIR / "rttrace.go")
        subprocess.run(
            ["go", "run", str(HERE / "go" / "instrument.go"), str(src), module],
            check=True, env=env, cwd=work,
        )
        expected = len(list(src.rglob(MAIN_FILE)))
        run_env = {**env, "RTTRACE_DIR": str(raw), "TMPDIR": str(tmp)}
        result = subprocess.run(["go", *TEST_ARGS], cwd=src, env=run_env, check=False)
        traces = sorted(raw.glob("*.tsv"))
        if len(traces) < expected:
            raise SystemExit(
                f"only {len(traces)} of {expected} test packages wrote a trace "
                f"(go test exited {result.returncode}); rerun"
            )
        if result.returncode != 0:
            print(f"warning: go test exited {result.returncode}; every package still "
                  "wrote its trace, so the capture is kept", file=sys.stderr)
        calls = []
        for trace in traces:
            with trace.open(encoding="utf-8") as handle:
                calls.extend(parse_trace(handle, src))
        version = subprocess.run(
            ["go", "env", "GOVERSION"], capture_output=True, text=True, check=True, env=env,
        ).stdout.strip()
        artifact = common.build_artifact(
            project=args.project, ref=ref, sha=sha, language="go",
            tool=f"{version} entry-hook instrumentation (runtime.Callers)",
            workload="the module's own tests on an instrumented copy: go " + " ".join(
                a if " " not in a else f"'{a}'" for a in TEST_ARGS),
            command=f"python3 tests/runtime/capture/go.py --project {args.project} "
                    f"--checkout /tmp/callix-baseline/{args.project.replace('/', '__')}",
            calls=calls,
        )
        common.write_artifact(output, artifact)
        print(f"{output}: {len(artifact['functions'])} functions, "
              f"{len(artifact['edges'])} edges")
    finally:
        if not args.keep and not args.work:
            shutil.rmtree(work, ignore_errors=True)
    return 0


if __name__ == "__main__":
    sys.exit(main())
