// Package rttrace records which function called which, once per call, for a
// runtime call-graph capture. Injected by the callix runtime capture; never
// part of the project.
package rttrace

import (
	"bufio"
	"fmt"
	"os"
	"path/filepath"
	"runtime"
	"strings"
	"sync"
)

const depth = 6

var (
	mu     sync.Mutex
	counts = map[[depth]uintptr]uint64{}
)

// E records the call of the function that calls it.
func E() {
	var key [depth]uintptr
	runtime.Callers(2, key[:])
	mu.Lock()
	counts[key]++
	mu.Unlock()
}

// skip reports frames that stand between a written call and its callee:
// compiler wrappers and the runtime's defer machinery.
func skip(frame runtime.Frame) bool {
	if frame.File == "<autogenerated>" || strings.HasSuffix(frame.Function, "-fm") {
		return true
	}
	switch frame.Function {
	case "runtime.deferreturn", "runtime.gopanic", "runtime.deferCallSave",
		"runtime.panicmem", "runtime.sigpanic":
		return true
	}
	return false
}

func entry(pc uintptr) (string, string, int) {
	fn := runtime.FuncForPC(pc)
	if fn == nil {
		return "", "", 0
	}
	file, line := fn.FileLine(fn.Entry())
	return fn.Name(), file, line
}

// Dump appends the recorded calls to $RTTRACE_DIR/<pid>.tsv.
func Dump() {
	dir := os.Getenv("RTTRACE_DIR")
	if dir == "" {
		return
	}
	mu.Lock()
	defer mu.Unlock()
	f, err := os.Create(filepath.Join(dir, fmt.Sprintf("%d.tsv", os.Getpid())))
	if err != nil {
		fmt.Fprintln(os.Stderr, "rttrace:", err)
		return
	}
	defer f.Close()
	w := bufio.NewWriter(f)
	defer w.Flush()
	merged := map[[2]string]uint64{}
	for key, n := range counts {
		calleeName, calleeFile, calleeLine := entry(key[0])
		frames := runtime.CallersFrames(key[1:])
		caller := ""
		for {
			frame, more := frames.Next()
			if frame.PC == 0 {
				break
			}
			if !skip(frame) {
				name, file, line := entry(frame.PC)
				caller = fmt.Sprintf("%s\t%s\t%d", name, file, line)
				break
			}
			if !more {
				break
			}
		}
		if caller == "" {
			continue
		}
		callee := fmt.Sprintf("%s\t%s\t%d", calleeName, calleeFile, calleeLine)
		merged[[2]string{caller, callee}] += n
	}
	for k, n := range merged {
		fmt.Fprintf(w, "%s\t%s\t%d\n", k[0], k[1], n)
	}
}
